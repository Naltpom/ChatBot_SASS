const DICTS: Record<Lang, Dict> = { en, fr, es, ru }

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('gh-lang')
    if (saved === 'en' || saved === 'fr' || saved === 'es' || saved === 'ru') return saved
  } catch { /* stockage indisponible */ }
  const nav = (typeof navigator !== 'undefined' && navigator.language?.toLowerCase().slice(0, 2)) || 'en'
  return (['fr', 'es', 'ru'] as const).includes(nav as 'fr') ? (nav as Lang) : 'en'
}

const Ctx = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void }>({ lang: 'en', t: en, setLang: () => {} })

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  useEffect(() => { document.documentElement.lang = lang }, [lang])
  const setLang = (l: Lang) => {
    setLangState(l)
    try { localStorage.setItem('gh-lang', l) } catch { /* rien */ }
  }
  return <Ctx.Provider value={{ lang, t: DICTS[lang], setLang }}>{children}</Ctx.Provider>
}

export const useI18n = () => useContext(Ctx)

export const euros = (cents: number) => `${(cents / 100).toFixed(2).replace('.', ',')} €`

export const compact = (n: number, lang: Lang) =>
  new Intl.NumberFormat(lang, { notation: n >= 10000 ? 'compact' : 'standard', maximumFractionDigits: 1 }).format(n)
